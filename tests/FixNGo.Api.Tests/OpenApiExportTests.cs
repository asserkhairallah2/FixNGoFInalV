using System.Text;
using System.Text.Json;
using FluentAssertions;

namespace FixNGo.Api.Tests;

/// <summary>Exports the real Swagger/OpenAPI document to docs/API.md as a readable endpoint catalogue.</summary>
[Collection("api")]
public sealed class OpenApiExportTests(ApiTestHost host)
{
    [Fact]
    public async Task SwaggerDocument_IsServed_AndExportedToApiMd()
    {
        using var anon = host.Anon();
        var res = await anon.GetAsync("/swagger/v1/swagger.json");
        res.EnsureSuccessStatusCode();
        var json = await res.Content.ReadAsStringAsync();
        using var doc = JsonDocument.Parse(json);
        var root = doc.RootElement;
        root.GetProperty("openapi").GetString().Should().StartWith("3.");

        var md = new StringBuilder();
        md.AppendLine("# FixNGo API v1 (generated from OpenAPI)");
        md.AppendLine();
        md.AppendLine("Generated by `OpenApiExportTests` from `/swagger/v1/swagger.json` — the live Swagger document emitted by ASP.NET Core. Do not edit by hand; re-run the API tests to regenerate.");
        md.AppendLine();
        md.AppendLine($"**Title:** {root.GetProperty("info").GetProperty("title").GetString()} | **Version:** {root.GetProperty("info").GetProperty("version").GetString()} | **Format:** {root.GetProperty("openapi").GetString()}");
        md.AppendLine();
        md.AppendLine("All endpoints are relative to `/`. The document declares a global Bearer security requirement; endpoints that are genuinely public at runtime (health, status, auth, lookups) are noted in the verification matrix.");
        md.AppendLine("For the exact per-role allow/deny matrix, see `docs/evidence/test-output/authz-matrix.md`.");
        md.AppendLine();
        md.AppendLine("| Method | Path | Summary | Security |");
        md.AppendLine("|---|---|---|---|");

        // Swashbuckle emits AddSecurityRequirement at the document root (global), not on
        // each operation. An operation-level override may still be present.
        var globalSecurity = root.TryGetProperty("security", out var gs) && gs.GetArrayLength() > 0;
        var paths = root.GetProperty("paths");
        foreach (var path in paths.EnumerateObject())
        {
            foreach (var op in path.Value.EnumerateObject())
            {
                var method = op.Name.ToUpperInvariant();
                if (!new[] { "GET", "POST", "PUT", "PATCH", "DELETE" }.Contains(method)) continue;
                var summary = op.Value.TryGetProperty("summary", out var s) ? s.GetString() ?? "" : "";
                var perOp = op.Value.TryGetProperty("security", out var sec) && sec.GetArrayLength() > 0;
                var noSec = op.Value.TryGetProperty("security", out var ns) && ns.GetArrayLength() == 0;
                var security = noSec ? "none" : (perOp || globalSecurity ? "Bearer" : "none");
                if (string.IsNullOrEmpty(summary))
                    summary = path.Name.Split('/').Last().Replace("{", "").Replace("}", "");
                summary = summary.Replace("|", "\\|");
                md.AppendLine($"| {method} | `{path.Name}` | {summary} | {security} |");
            }
        }

        var dir = Path.Combine(Http.RepoRoot(), "docs");
        Directory.CreateDirectory(dir);
        await File.WriteAllTextAsync(Path.Combine(dir, "API.md"), md.ToString());

        File.ReadAllText(Path.Combine(dir, "API.md")).Should().Contain("`/api/v1/requests`");
    }
}
