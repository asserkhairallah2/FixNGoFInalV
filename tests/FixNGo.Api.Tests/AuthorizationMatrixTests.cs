using System.Net;
using System.Text;
using FixNGo.Domain;
using FluentAssertions;

namespace FixNGo.Api.Tests;

/// <summary>
/// Exercises every representative endpoint as {anonymous, each role} and asserts the
/// expected RBAC boundary. Also emits docs/evidence/test-output/authz-matrix.md.
/// </summary>
[Collection("api")]
public sealed class AuthorizationMatrixTests(ApiTestHost host)
{
    private static readonly (string Label, HttpMethod Method, string Path, object? Body, Role[] Allowed)[] Routes =
    [
        ("vehicles.list", HttpMethod.Get, "/api/v1/vehicles", null, [Role.CarOwner]),
        ("vehicles.create", HttpMethod.Post, "/api/v1/vehicles",
            new { make = "Toyota", model = "Corolla", year = 2022, plate = "ABC1234", color = "White", fuel = "Petrol" }, [Role.CarOwner]),
        ("admin.dashboard", HttpMethod.Get, "/api/v1/admin/dashboard", null, [Role.Admin]),
        ("admin.users", HttpMethod.Get, "/api/v1/admin/users", null, [Role.Admin]),
        ("admin.settings", HttpMethod.Get, "/api/v1/admin/settings", null, [Role.Admin]),
        ("admin.kycQueue", HttpMethod.Get, "/api/v1/admin/kyc/queue", null, [Role.Admin]),
        ("providers.me", HttpMethod.Get, "/api/v1/providers/me", null, [Role.Mechanic, Role.TowCaptain]),
        ("providers.nearby", HttpMethod.Get, "/api/v1/providers/nearby?lat=30&lng=31", null, [Role.Mechanic, Role.TowCaptain]),
        ("offers.mine", HttpMethod.Get, "/api/v1/offers", null, [Role.Mechanic, Role.TowCaptain]),
        ("payments.wallet", HttpMethod.Get, "/api/v1/payments/wallet", null, [Role.Mechanic, Role.TowCaptain]),
        ("payments.earnings", HttpMethod.Get, "/api/v1/payments/earnings", null, [Role.Mechanic, Role.TowCaptain]),
        ("centerAdmin.profile", HttpMethod.Get, "/api/v1/center-admin/profile", null, [Role.ServiceCenter]),
        ("requests.list", HttpMethod.Get, "/api/v1/requests", null, [Role.CarOwner, Role.Mechanic, Role.TowCaptain, Role.ServiceCenter, Role.Admin]),
        ("notifications.list", HttpMethod.Get, "/api/v1/notifications", null, [Role.CarOwner, Role.Mechanic, Role.TowCaptain, Role.ServiceCenter, Role.Admin]),
        ("chat.threads", HttpMethod.Get, "/api/v1/chat/threads", null, [Role.CarOwner, Role.Mechanic, Role.TowCaptain, Role.ServiceCenter, Role.Admin]),
        ("support.tickets", HttpMethod.Get, "/api/v1/support/tickets", null, [Role.CarOwner, Role.Mechanic, Role.TowCaptain, Role.ServiceCenter, Role.Admin]),
        ("lookups.bootstrap", HttpMethod.Get, "/api/v1/lookups/bootstrap", null, [Role.CarOwner, Role.Mechanic, Role.TowCaptain, Role.ServiceCenter, Role.Admin]),
    ];

    private static readonly (string Email, Role Role)[] Identities =
    [
        (ApiTestHost.Owner, Role.CarOwner),
        (ApiTestHost.Mechanic, Role.Mechanic),
        (ApiTestHost.Captain, Role.TowCaptain),
        (ApiTestHost.Center, Role.ServiceCenter),
        (ApiTestHost.Admin, Role.Admin),
    ];

    [Fact]
    public async Task Anonymous_IsRejectedOnEveryProtectedRoute_AndAllowedOnPublicOnes()
    {
        using var anon = host.Anon();
        foreach (var route in Routes)
        {
            var (code, _) = await Http.Call(anon, route.Method, route.Path, route.Body);
            code.Should().Be(HttpStatusCode.Unauthorized, $"{route.Label} must require authentication");
        }
        foreach (var path in new[] { "/health", "/api/v1/system/status", "/api/v1/support/faqs" })
        {
            var (code, _) = await Http.Get(anon, path);
            code.Should().Be(HttpStatusCode.OK, $"{path} is public");
        }
    }

    [Fact]
    public async Task RoleBoundaries_MatchThePolicyMatrix_AndEmitEvidence()
    {
        var md = new StringBuilder();
        md.AppendLine("# API authorisation matrix");
        md.AppendLine();
        md.AppendLine("Generated by `AuthorizationMatrixTests`. `200/201/204` = allowed; `403` = forbidden; `401` = unauthenticated.");
        md.AppendLine();
        md.AppendLine("| Endpoint | Method | Anonymous | CarOwner | Mechanic | TowCaptain | ServiceCenter | Admin | Expected |");
        md.AppendLine("|---|---|---|---|---|---|---|---|---|");

        foreach (var route in Routes)
        {
            var observed = new List<string>();
            using (var anon = host.Anon())
            {
                var (code, _) = await Http.Call(anon, route.Method, route.Path, route.Body);
                observed.Add(((int)code).ToString());
                code.Should().Be(HttpStatusCode.Unauthorized, route.Label);
            }
            foreach (var (email, role) in Identities)
            {
                using var client = host.Client(email);
                var (code, _) = await Http.Call(client, route.Method, route.Path, route.Body);
                observed.Add(((int)code).ToString());
                var expectedAllowed = route.Allowed.Contains(role);
                if (expectedAllowed)
                    ((int)code).Should().NotBe(401).And.NotBe(403,
                        $"{route.Label} should allow {role} (got {(int)code})");
                else
                    code.Should().Be(HttpStatusCode.Forbidden,
                        $"{route.Label} should forbid {role} (got {(int)code})");
            }
            md.AppendLine($"| `{route.Path}` | {route.Method} | {observed[0]} | {observed[1]} | {observed[2]} | {observed[3]} | {observed[4]} | {observed[5]} | {string.Join(",", route.Allowed)} |");
        }

        var dir = Path.Combine(Http.RepoRoot(), "docs", "evidence", "test-output");
        Directory.CreateDirectory(dir);
        await File.WriteAllTextAsync(Path.Combine(dir, "authz-matrix.md"), md.ToString());
    }
}
